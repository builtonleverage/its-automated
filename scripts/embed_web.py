"""Embed everything in web/ into the firmware as gzipped byte arrays.

Runs automatically before each PlatformIO build (see platformio.ini) and
writes src/web_assets.h. Can also be run by hand:

    python scripts/embed_web.py
"""
import gzip
import os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB_DIR = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "web_assets.h")

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".webmanifest": "application/manifest+json",
    ".json": "application/json",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
}


def main():
    entries = []
    chunks = []
    for name in sorted(os.listdir(WEB_DIR)):
        path = os.path.join(WEB_DIR, name)
        ext = os.path.splitext(name)[1].lower()
        if not os.path.isfile(path) or ext not in MIME:
            continue
        with open(path, "rb") as f:
            raw = f.read()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        ident = "asset_" + "".join(c if c.isalnum() else "_" for c in name)
        body = ",".join(str(b) for b in data)
        chunks.append("static const uint8_t %s[] PROGMEM = {%s};" % (ident, body))
        entries.append('  {"/%s", "%s", %s, %d},' % (name, MIME[ext], ident, len(data)))
        print("embed_web: %-24s %6d -> %6d bytes" % (name, len(raw), len(data)))

    lines = [
        "// Generated by scripts/embed_web.py - do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct WebAsset { const char *path; const char *mime; const uint8_t *data; size_t len; };",
        "",
    ]
    lines += chunks
    lines += ["", "static const WebAsset WEB_ASSETS[] = {"] + entries + ["};"]
    lines += ["static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);", ""]

    content = "\n".join(lines)
    old = None
    if os.path.exists(OUT):
        with open(OUT) as f:
            old = f.read()
    if old != content:
        with open(OUT, "w") as f:
            f.write(content)


main()
